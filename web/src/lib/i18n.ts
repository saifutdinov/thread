const dicts = { ru, en };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem('lang');
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    /* storage blocked: fall back to the browser language */
  }
  return navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export const lang = signal<Lang>(initialLang());

function pluralIndex(n: number): number {
  if (lang.value === 'en') return n === 1 ? 0 : 1;
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return 0;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return 1;
  return 2;
}

export function t(key: string, params: Record<string, string | number> = {}): string {
  let e: Entry = dicts[lang.value][key] ?? ru[key] ?? key;
  if (Array.isArray(e)) e = e[pluralIndex(Number(params.n ?? 0))] ?? e[e.length - 1];
  return e.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? ''));
}

export function errText(e: unknown): string {
  const code = (e as { code?: string })?.code;
  const key = 'err.' + code;
  return code && key in ru ? t(key) : t('err.generic');
}

const locale = () => (lang.value === 'ru' ? 'ru-RU' : 'en-GB');
const sameDay = (a: Date, b: Date) => a.toDateString() === b.toDateString();

export const fmtTime = (ms: number) =>
  new Date(ms).toLocaleTimeString(locale(), { hour: '2-digit', minute: '2-digit' });

export function fmtDay(ms: number): string {
  const d = new Date(ms);
  const now = new Date();
  if (sameDay(d, now)) return t('chat.today');
  if (sameDay(d, new Date(now.getTime() - 864e5))) return t('chat.yesterday');
  return d.toLocaleDateString(locale(), {
    day: 'numeric',
    month: 'long',
    year: d.getFullYear() === now.getFullYear() ? undefined : 'numeric',
  });
}

// fmtListTime: time today, weekday this week, else a short date.
export function fmtListTime(ms: number): string {
  const d = new Date(ms);
  const now = new Date();
  if (sameDay(d, now)) return fmtTime(ms);
  if (now.getTime() - ms < 6 * 864e5) return d.toLocaleDateString(locale(), { weekday: 'short' });
  return d.toLocaleDateString(locale(), { day: '2-digit', month: '2-digit', year: '2-digit' });
}

export function fmtLastSeen(ms: number): string {
  const d = new Date(ms);
  const now = new Date();
  if (sameDay(d, now)) return t('chat.lastSeen', { when: t('time.at', { t: fmtTime(ms) }) });
  if (sameDay(d, new Date(now.getTime() - 864e5)))
    return t('chat.lastSeen', { when: t('time.yesterdayAt', { t: fmtTime(ms) }) });
  return t('chat.lastSeen', { when: d.toLocaleDateString(locale(), { day: 'numeric', month: 'short' }) });
}

export const fmtDate = (ms: number) => new Date(ms).toLocaleDateString(locale(), { day: 'numeric', month: 'short' });
